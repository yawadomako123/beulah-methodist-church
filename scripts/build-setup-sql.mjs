/**
 * Builds database/setup.sql: the full schema plus default data, as one script that can be
 * pasted into the Neon SQL Editor. It also records the migration in Drizzle's journal table,
 * so `npm run db:migrate` later knows the schema is already in place.
 *
 *   node scripts/build-setup-sql.mjs
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const journal = JSON.parse(await readFile("drizzle/meta/_journal.json", "utf8"));
const parts = [];

for (const entry of journal.entries) {
  const raw = await readFile(`drizzle/${entry.tag}.sql`, "utf8");
  const hash = createHash("sha256").update(raw).digest("hex");
  const statements = raw
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => (s.endsWith(";") ? s : `${s};`));
  parts.push(`-- Migration ${entry.tag}\n${statements.join("\n\n")}`);
  parts.push(
    `INSERT INTO "drizzle"."__drizzle_migrations" ("hash", "created_at") VALUES ('${hash}', ${entry.when});`,
  );
}

const sql = `-- =====================================================================
-- Beulah Methodist Church: database setup
-- Paste this whole file into the Neon SQL Editor and run it ONCE on an
-- empty database. It creates every table and adds the default data.
-- (Generated by scripts/build-setup-sql.mjs; do not edit by hand.)
-- =====================================================================

BEGIN;

-- Drizzle's migration journal, so "npm run db:migrate" skips what is already applied.
CREATE SCHEMA IF NOT EXISTS "drizzle";
CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (
  "id" SERIAL PRIMARY KEY,
  "hash" text NOT NULL,
  "created_at" bigint
);

${parts.join("\n\n")}

-- ---------------------------------------------------------------------
-- Default data
-- ---------------------------------------------------------------------

-- Church settings (all editable later under Admin > Settings)
INSERT INTO "settings" ("key", "value") VALUES
  ('churchName', 'Beulah Methodist Church'),
  ('shortName', 'Beulah Methodist'),
  ('currency', 'GHS'),
  ('timezone', 'Africa/Accra'),
  ('locale', 'en-GB'),
  ('address', ''),
  ('phone', ''),
  ('email', ''),
  ('website', '')
ON CONFLICT ("key") DO NOTHING;

-- Giving funds
INSERT INTO "funds" ("name", "description") VALUES
  ('Tithe', 'Tithes (one tenth)'),
  ('Sunday Offering', 'General offering at services'),
  ('Thanksgiving', 'Thanksgiving offerings'),
  ('Harvest', 'Annual harvest thanksgiving'),
  ('Building Fund', 'Church building and projects'),
  ('Welfare', 'Support for members in need'),
  ('Missions & Evangelism', 'Outreach and mission work'),
  ('Class Dues', 'Class meeting dues and contributions')
ON CONFLICT ("name") DO NOTHING;

-- Starter groups (rename or delete as needed)
INSERT INTO "groups" ("name", "type", "meeting_day", "meeting_time", "location") VALUES
  ('Singing Band', 'choir', 'Thursday', '17:00', 'Church premises'),
  ('Church Choir', 'choir', 'Saturday', '16:00', 'Church premises'),
  ('Women''s Fellowship', 'fellowship', 'Friday', '17:30', 'Church premises'),
  ('Men''s Fellowship', 'fellowship', 'Friday', '17:30', 'Church premises'),
  ('Youth Fellowship', 'youth', 'Saturday', '15:00', 'Church premises'),
  ('Girls'' Fellowship', 'youth', 'Saturday', '15:00', 'Church premises'),
  ('Boys'' Brigade', 'youth', 'Saturday', '09:00', 'Church premises'),
  ('Sunday School', 'sunday_school', 'Sunday', '08:00', 'Church premises'),
  ('Guild', 'fellowship', 'Wednesday', '17:30', 'Church premises'),
  ('Leaders'' Meeting', 'committee', NULL, NULL, 'Church office');

-- Welcome notice
INSERT INTO "announcements" ("title", "body", "pinned") VALUES
  ('Welcome to the Beulah Methodist Church app',
   'Members can sign in with their Google account to see church announcements, upcoming events and their own giving history. Install it on your phone from the menu with "Install app".',
   true);

COMMIT;
`;

await mkdir("database", { recursive: true });
await writeFile("database/setup.sql", sql);
console.log("✓ database/setup.sql");
